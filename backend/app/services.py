DEMO_THRESHOLD_SOURCE = (
    "Demo setting derived from the simulated record (93rd / 98.5th / 99.7th percentile of stage). "
    "Not an official threshold — replace with values agreed with the responsible agency."
)

_forecast_cache: dict[str, tuple[tuple, dict]] = {}
_cache_lock = threading.Lock()
_station_locks: dict[str, threading.Lock] = {}


# ---------------------------------------------------------------- importing


def upsert_observations(session: Session, frame: pd.DataFrame, dataset: Dataset) -> int:
    """Insert or update readings; a column missing in the new row keeps the stored value."""
    if frame.empty:
        return 0
    records = [
        {
            "station_id": r.station_id,
            "observed_at": r.observed_at.to_pydatetime(),
            "water_level_m": None if pd.isna(r.water_level_m) else float(r.water_level_m),
            "rainfall_mm": None if pd.isna(r.rainfall_mm) else float(r.rainfall_mm),
            "dataset_id": dataset.id,
        }
        for r in frame.itertuples(index=False)
    ]
    dialect = session.get_bind().dialect.name
    insert_fn = postgresql.insert if dialect == "postgresql" else sqlite.insert
    for start in range(0, len(records), 2000):
        stmt = insert_fn(Observation).values(records[start : start + 2000])
        stmt = stmt.on_conflict_do_update(
            index_elements=["station_id", "observed_at"],
            set_={
                "water_level_m": func.coalesce(stmt.excluded.water_level_m, Observation.water_level_m),
                "rainfall_mm": func.coalesce(stmt.excluded.rainfall_mm, Observation.rainfall_mm),
                "dataset_id": stmt.excluded.dataset_id,
            },
        )
        session.execute(stmt)
    return len(records)


def ensure_station(session: Session, meta: StationMetadata, thresholds: dict, is_simulated: bool, source: str) -> Station:
    station = session.get(Station, meta.id)
    if station is None:
        station = Station(
            id=meta.id,
            name=meta.name,
            river=meta.river,
            latitude=meta.latitude,
            longitude=meta.longitude,
            timezone=meta.timezone,
            is_simulated=is_simulated,
            threshold_source=source,
            **thresholds,
        )
        session.add(station)
    return station


def seed_demo(session: Session, force: bool = False) -> Dataset | None:
    """Load the simulated scenario if the database has no stations (or force=True)."""
    if not force and session.scalar(select(func.count()).select_from(Station)):
        return None
    if force:
        sim_ids = select(Station.id).where(Station.is_simulated)
        session.execute(delete(Observation).where(Observation.station_id.in_(sim_ids)))
        session.execute(delete(Station).where(Station.is_simulated))
        session.execute(delete(Dataset).where(Dataset.is_simulated))
        session.flush()

    provider = SimulatedProvider()
    frame = provider.observations()
    dataset = Dataset(
        name=provider.name,
        source_type="simulated",
        source_detail="Generated by app/providers/simulated.py: stochastic storms → gamma unit hydrograph → rating curve.",
        is_simulated=True,
        rows_received=len(frame),
        period_start=frame["observed_at"].min().to_pydatetime(),
        period_end=frame["observed_at"].max().to_pydatetime(),
        source_timezone="UTC",
        validation={"note": "Synthetic data; not observations."},
    )
    session.add(dataset)
    session.flush()
    for meta in provider.stations():
        levels = frame.loc[frame["station_id"] == meta.id, "water_level_m"]
        ensure_station(session, meta, {**demo_thresholds(levels), "rise_rate_advisory_m_per_h": 0.15}, True, DEMO_THRESHOLD_SOURCE)
    session.flush()
    dataset.rows_imported = upsert_observations(session, frame, dataset)
    session.commit()
    clear_forecast_cache()
    return dataset


# ---------------------------------------------------------------- loading


def station_observations(session: Session, station_id: str) -> pd.DataFrame:
    rows = session.execute(
        select(Observation.observed_at, Observation.water_level_m, Observation.rainfall_mm)
        .where(Observation.station_id == station_id)
        .order_by(Observation.observed_at)
    ).all()
    frame = pd.DataFrame(rows, columns=["observed_at", "water_level_m", "rainfall_mm"])
    if not frame.empty:
        frame["observed_at"] = pd.to_datetime(frame["observed_at"], utc=True)
    return frame.astype({"water_level_m": float, "rainfall_mm": float})


def _fingerprint(session: Session, station_id: str) -> tuple:
    return tuple(
        session.execute(
            select(func.count(), func.max(Observation.observed_at), func.max(Observation.dataset_id)).where(
                Observation.station_id == station_id
            )
        ).one()
    )


def station_provenance(session: Session, station_id: str) -> list[dict]:
    rows = session.execute(
        select(Dataset, func.count(Observation.id), func.min(Observation.observed_at), func.max(Observation.observed_at))
        .join(Observation, Observation.dataset_id == Dataset.id)
        .where(Observation.station_id == station_id)
        .group_by(Dataset.id)
    ).all()
    return [
        {
            "dataset_id": ds.id,
            "name": ds.name,
            "source_type": ds.source_type,
            "is_simulated": ds.is_simulated,
            "readings": n,
            "first": as_utc(first).isoformat(),
            "last": as_utc(last).isoformat(),
        }
        for ds, n, first, last in rows
    ]


# ---------------------------------------------------------------- forecasting


def clear_forecast_cache() -> None:
    with _cache_lock:
        _forecast_cache.clear()


def station_forecast(session: Session, station: Station) -> dict:
    """Pipeline output + recent history for one station, cached until its data changes.
    A per-station lock makes concurrent callers wait for one computation."""
    with _cache_lock:
        lock = _station_locks.setdefault(station.id, threading.Lock())
    with lock:
        key = _fingerprint(session, station.id)
        with _cache_lock:
            hit = _forecast_cache.get(station.id)
        if hit and hit[0] == key:
            return hit[1]
        result = _compute_forecast(session, station)
        with _cache_lock:
            _forecast_cache[station.id] = (key, result)
        return result


def _compute_forecast(session: Session, station: Station) -> dict:
    obs = station_observations(session, station.id)
    if obs.empty or obs["water_level_m"].notna().sum() == 0:
        result = {"status": "no_data", "message": "No water-level readings for this station yet."}
    else:
        hourly, resample_summary = resample_hourly(obs)
        try:
            result = {"status": "ok", **forecast_station(hourly)}
        except InsufficientDataError as exc:
            result = {"status": "insufficient_data", "message": str(exc)}
        recent = hourly.iloc[-24 * 7 :]
        result["history"] = [
            {
                "time": t.isoformat(),
                "water_level_m": None if pd.isna(r.water_level_m) else round(float(r.water_level_m), 3),
                "rainfall_mm": round(float(r.rainfall_mm), 2),
            }
            for t, r in recent.iterrows()
        ]
        result["preprocessing"] = resample_summary.as_dict()
        result["rain_last_24h_mm"] = round(float(hourly["rainfall_mm"].iloc[-24:].sum()), 1)
        result["last_observation_at"] = obs["observed_at"].max().isoformat()
    return result


def thresholds_of(station: Station) -> Thresholds:
    return Thresholds(
        station.advisory_level_m, station.warning_level_m, station.critical_level_m, station.rise_rate_advisory_m_per_h
    )


def station_weather(station: Station) -> dict | None:
    try:
        return open_meteo.fetch_forecast(station.latitude, station.longitude)
    except open_meteo.WeatherUnavailable:
        return None


def station_risk(station: Station, forecast: dict, weather: dict | None) -> dict | None:
    if forecast.get("status") != "ok":
        return None
    horizons = [
        {
            "horizon_h": h["horizon_h"],
            "point_m": h["point_m"],
            "hi80_m": h["hi80_m"],
            "skill": h["skill_vs_persistence"].get(h["selected_model"]),
        }
        for h in forecast["horizons"]
    ]
    last = datetime.fromisoformat(forecast["last_observation_at"])
    return assess(
        thresholds_of(station),
        forecast["current_level_m"],
        forecast["current_slope_m_per_h"],
        horizons,
        rain_last_24h_mm=forecast.get("rain_last_24h_mm"),
        rain_next_24h_mm=weather["summary"]["next_24h_mm"] if weather else None,
        data_age_hours=(datetime.now(timezone.utc) - last).total_seconds() / 3600,
        is_simulated=station.is_simulated,
    ).as_dict()


def station_summary(station: Station) -> dict:
    return {
        "id": station.id,
        "name": station.name,
        "river": station.river,
        "latitude": station.latitude,
        "longitude": station.longitude,
        "timezone": station.timezone,
        "is_simulated": station.is_simulated,
        "thresholds": {
            "advisory_m": station.advisory_level_m,
            "warning_m": station.warning_level_m,
            "critical_m": station.critical_level_m,
            "rise_rate_m_per_h": station.rise_rate_advisory_m_per_h,
            "source": station.threshold_source,
        },
    }


def full_station_report(session: Session, station: Station, include_weather: bool = True) -> dict:
    forecast = station_forecast(session, station)
    weather = station_weather(station) if include_weather else None
    last = forecast.get("last_observation_at")
    age_h = (utcnow() - datetime.fromisoformat(last)).total_seconds() / 3600 if last else None
    return {
        "station": station_summary(station),
        "forecast": forecast,
        "risk": station_risk(station, forecast, weather),
        "weather": weather,
        "freshness": {
            "last_observation_at": last,
            "age_hours": round(age_h, 2) if age_h is not None else None,
            "timezone": "UTC",
            "data_kind": "simulated" if station.is_simulated else "observed",
        },
        "provenance": station_provenance(session, station.id),
    }
